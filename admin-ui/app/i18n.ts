function readLang(): Lang {
  if (typeof window === 'undefined') return 'uk';
  try {
    return window.localStorage.getItem(LangKey) === 'en' ? 'en' : 'uk';
  } catch {
    return 'uk';
  }
}

/** Language of this page load (the static export renders "uk"; the browser reads the saved choice). */
