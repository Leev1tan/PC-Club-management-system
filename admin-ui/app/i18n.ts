/** Saves the language and reloads the page (every screen reads `t` once). */
export function setLang(next: Lang) {
  try { window.localStorage.setItem(LangKey, next); } catch { /* private mode: this page load only */ }
  window.location.reload();
}

/** Text of a server error code with its arguments ({0}, {1} ...), or null for an unknown code. */
export function errorMessage(code: string, args?: string[] | null): string | null {
  const text = t.errors[code];
  if (!text) return null;
  return text.replace(/\{(\d+)\}/g, (_, i) => args?.[Number(i)] ?? '');
}

/** Replaces {name} placeholders. */
export function fmt(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key) => (key in values ? String(values[key]) : `{${key}}`));
}

export const money = (n: number | null | undefined) => (n ?? 0).toFixed(2);
/** Amount with the club currency symbol: "150.00 ₴", "12.50 €". */
export const cash = (n: number | null | undefined) => `${money(n)} ${t.currency}`;

export const dateTime = (iso: string, seconds = false) => {
  const d = new Date(iso);
  return `${d.toLocaleDateString(locale)} ${d.toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit', ...(seconds ? { second: '2-digit' } : {}) })}`;
};
export const clock = (iso: string) => new Date(iso).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' });

// ===== Club time zone (from /api/auth/me): reservations, orders and lockouts show club times =====
let clubZone: string | undefined;
/** Sets the club time zone (IANA id); an unknown id keeps the browser's zone. */
export function setClubZone(zone: string | null | undefined) {
  try {
    if (zone) new Intl.DateTimeFormat('en', { timeZone: zone }).format(0);
    clubZone = zone || undefined;
  } catch {
    clubZone = undefined;
  }
}
export const clubZoneId = () => clubZone;
/** HH:mm in the club time zone. */
export const clubClock = (iso: string) => new Date(iso).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit', timeZone: clubZone });
/** Date and HH:mm in the club time zone. */
export const clubDateTime = (iso: string) =>
  `${new Date(iso).toLocaleDateString(locale, { timeZone: clubZone })} ${clubClock(iso)}`;
/** Today's date in the club time zone as YYYY-MM-DD. */
export const clubToday = (offsetDays = 0) => {
  const d = new Date(Date.now() + offsetDays * 86400000);
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: clubZone, year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(d);
  const get = (type: string) => parts.find(p => p.type === type)?.value ?? '';
  return `${get('year')}-${get('month')}-${get('day')}`;
};

export function methodLabel(method: string | null | undefined): string {
  if (!method) return t.none;
  return method.split('+').map(m => (t.pay as Record<string, string>)[m] ?? m).join(' + ');
}

export function ledgerTypeLabel(type: string): string {
  return t.ledgerTypes[type] ?? type;
}

/** ISO weekdays (1 = Monday) as text; consecutive days become ranges: [1,2,3,4,5,7] -> "Пн–Пт, Нд". */
export function daysLabel(days: number[]): string {
  if (days.length === 7) return t.allDays;
  const sorted = [...days].sort((a, b) => a - b);
  const parts: string[] = [];
  for (let i = 0; i < sorted.length; i++) {
    let j = i;
    while (j + 1 < sorted.length && sorted[j + 1] === sorted[j] + 1) j++;
    parts.push(j - i >= 2 ? `${t.days[sorted[i] - 1]}–${t.days[sorted[j] - 1]}` : sorted.slice(i, j + 1).map(d => t.days[d - 1]).join(', '));
    i = j;
  }
  return parts.join(', ');
}
